/**
 * One-time: generate the Ed25519 license keypair.
 *   npm run license:genkeys
 * Writes the public key into src/license/public-key.ts (committed, shipped in the add-on)
 * and the private key into tools/.license-private.pem (git-ignored — keep this secret & backed up).
 * Re-running overwrites both: existing licenses stop validating, so do it only once.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateKeypair } from '../src/license/crypto.js';

const dir = path.dirname(fileURLToPath(import.meta.url));
const privPath = path.join(dir, '.license-private.pem');
const pubTsPath = path.join(dir, '..', 'src', 'license', 'public-key.ts');

if (fs.existsSync(privPath) && !process.argv.includes('--force')) {
  console.error(`Private key already exists: ${privPath}\nRe-run with --force to overwrite (this invalidates all existing licenses).`);
  process.exit(1);
}

const { publicKeyPem, privateKeyPem } = generateKeypair();
fs.writeFileSync(privPath, privateKeyPem, { mode: 0o600 });

const ts = `/**
 * Add-on's embedded license verification key (public — safe to publish).
 * Generated by tools/license-keygen.ts. The matching private key is tools/.license-private.pem (keep secret).
 */
export const LICENSE_PUBLIC_KEY = \`${publicKeyPem.trim()}\`;
`;
fs.writeFileSync(pubTsPath, ts);

console.log('Keypair generated.');
console.log(`  Private key: ${privPath}  (SECRET — back it up, never commit)`);
console.log(`  Public key : ${pubTsPath}  (commit this)`);
console.log('\nNext: issue a license with  npm run license:issue -- --cust "Name" --id ID --days 365 [--hwid INSTALL_ID]');
